const TITLES = [
  "Сказка о том, кто держал туман в руках",
  "Сказка о путнике, который остановился слушать",
  "Сказка о тихом свете за закрытой дверью",
  "Сказка о том, кто искал имя своему беспокойству",
  "Сказка о человеке, который вспомнил, как дышать",
  "Сказка о ключе, найденном в собственном кармане",
];

const hash = (s: string) => {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0;
  return Math.abs(h);
};

const soften = (s: string) => {
  const t = s.trim().replace(/[.!?]+$/, "");
  return t.charAt(0).toLowerCase() + t.slice(1);
};

export function buildMyth(a: MythAnswers): Myth {
  const seed = hash(Object.values(a).join("|"));
  const key = KEYS[seed % KEYS.length]!;
  const title = TITLES[(seed >> 3) % TITLES.length]!;

  const fog = soften(a.fog);
  const state = soften(a.state);
  const alive = soften(a.alive);
  const missing = soften(a.missing);

  const story = [
    `Жил человек, у которого в доме был один туман — ${fog}. Он не был врагом. Он приходил под утро, садился у стола и молчал так, что становилось слышно всё остальное.`,
    `Если бы кто-то спросил, как он живёт, человек ответил бы образом: ${state}. Он и сам не знал, откуда взялся этот образ, но он был точнее любого объяснения.`,
    `Он помнил день, когда всё было иначе: ${alive}. Тогда никто не подсказывал, что делать, — тело знало само. Этот день он носил с собой как тёплый камень в кармане и доставал редко, чтобы не стереть.`,
    `И была вещь, которой не хватало, — ${missing}. Он звал её по-разному, но она приходила только на настоящее имя. ${key.keyName} — так её зовут в этой сказке: ${key.keyLine}.`,
    `Однажды туман поднялся не потому, что человек его прогнал, а потому, что тот сделал свою работу: показал, где стоять больше нельзя. И человек сделал шаг — не героический, маленький, ровно в сторону того, чего просил.`,
    `Сказка не говорит, чем всё закончилось. Она говорит только, что человек перестал ждать, пока станет ясно, и начал двигаться внутри тумана — и туман впервые оказался не стеной, а дорогой.`,
  ];

  const question = `Если бы ${missing} было доступно вам уже сегодня — в чём именно, в одном маленьком действии, это было бы заметно?`;

  return { title, keyName: key.keyName, keyLine: key.keyLine, story, question };
}

